#!/usr/bin/env python3
"""Generate portable docs from CLI help without contacting or starting a daemon."""

import argparse
from pathlib import Path
import re
import subprocess
import sys


# Keep explicit: doctor/version ignore --help, and a new command must be
# checked for side effects before the generator is allowed to execute it.
HELP_COMMANDS = (
    "daemon", "join", "token", "login", "logout", "node", "promote", "sh",
    "exec", "cp", "ls", "logs", "audit", "start", "stop", "pause", "resume",
    "rm", "snapshot", "desktop", "expose",
)
# Service help varies by OS. The portable reference uses their root-help
# descriptions and points readers to their own binary for installer details.
ROOT_ONLY = {"doctor", "version", "up", "down"}
SUBCOMMANDS = {"token": ("create",), "snapshot": ("ls",)}


def help_text(binary, args):
    result = subprocess.run(
        [str(binary), *args], stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=10,
    )
    output = result.stdout.strip()
    # flag.ContinueOnError returns 2 for most commands, 125 for exec.
    if result.returncode not in (0, 2, 125) or "Usage" not in output:
        raise RuntimeError(f"help failed for {args!r}: exit {result.returncode}: {output}")
    return output.expandtabs(8)


def render(binary):
    root = help_text(binary, ["--help"])
    commands = re.findall(r"^  ([a-z]+) {2,}", root, re.MULTILINE)
    expected = set(HELP_COMMANDS) | ROOT_ONLY
    if set(commands) != expected or len(commands) != len(expected):
        raise RuntimeError("CLI commands changed; review help safety and update the generator: "
                           f"added={set(commands) - expected}, removed={expected - set(commands)}")
    parts = [
        "# Command reference",
        "<!-- Generated by scripts/generate-command-reference.py; do not edit. -->",
        "From this checkout's CLI help. Regenerate with:\n\n"
        "```sh\ngo build -o bin/boxpool ./cmd/boxpool\n"
        "python3 scripts/generate-command-reference.py --binary bin/boxpool\n```",
        "On Linux, use `sudo /usr/local/bin/boxpool` for the installed root daemon. "
        "On macOS, run as your user. See the [user guide](guide.md) for examples, "
        "state paths, environment variables and local versus remote commands. "
        "Flags precede positional arguments unless help shows otherwise.",
        "## All commands\n\n```text\n" + root + "\n```",
    ]
    for command in commands:
        parts.append("## " + command)
        if command in {"up", "down"}:
            parts.append(
                f"Installer help depends on the host OS. Run `boxpool {command} --help` "
                "on that host. See [service setup and cleanup](../README.md#2-start-the-head) "
                "and [state and upgrades](guide.md#state-logs-and-upgrades)."
            )
        elif command in ROOT_ONLY:
            description = re.search(rf"^  {command} +(.+)$", root, re.MULTILINE)[1]
            parts.append(f"```text\nboxpool {command}    # {description}\n```\n\n"
                         "This command has no flags; its description comes from root help.")
        else:
            parts.append("```text\n" + help_text(binary, [command, "--help"]) + "\n```")
            for sub in SUBCOMMANDS.get(command, ()):
                parts.append(f"### {command} {sub}\n\n```text\n"
                             + help_text(binary, [command, sub, "--help"]) + "\n```")
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "docs/commands.md")
    parser.add_argument("--check", action="store_true", help="fail if the checked-in reference is stale")
    args = parser.parse_args()
    generated = render(args.binary.resolve())
    if args.check:
        if not args.output.exists() or args.output.read_text() != generated:
            print(f"{args.output} is stale; regenerate the command reference", file=sys.stderr)
            return 1
        print("command reference is current")
    else:
        args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
